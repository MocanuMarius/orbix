// A disposable deck for phone inspection. Never reads or writes a player save.
import { newState, createRun, advanceMap, getSupportChoices, getChoices, selectNode, beginFlightAttempt, markFlightAttemptStarted, finishFlight, settleCheckpoint } from './model.mjs?v=reskin-3';
import { makeSkillCard } from './skill-cards.mjs?v=reskin-3';

export function prepareCardInspectorReward(run, cardId = 'harvest-rare') {
  if (run.cardReward && !run.cardReward.uiAcknowledged) return;
  const id = `sample-reward:${run.cardHistory.length}`;
  run.cardReward = { id, source: 'flight', claimed: false, card: makeSkillCard(cardId, id) };
}

// A full receipt stress case, still generated by the production flight and
// settlement code. These are disposable run inputs, never invented receipt rows.
function prepareLateGamePack(state) {
  const run = state.run;
  for (let chapter = 0; chapter < 2; chapter++) {
    run.mapFlights = 6;
    run.phase = 'map-clear';
    advanceMap(run);
  }
  run.stats = { flights: 16, attempts: 18, deaths: 2, collected: 236, elites: 4, events: 5, challenges: 9 };
  run.mapFlights = 4;
  run.cardSlots = 5;
  run.cardFutureCapacity = 9;
  run.cardCruisingSpeed = 3;
  run.cardCruisingSpeedUnlocked = 3;
  run.mountedCards = ['tight-packing-iii', 'wayfarers-purse', 'growth-ring', 'wind-feather', 'edge-reach']
    .map((id, i) => makeSkillCard(id, `sample:late:mounted:${i}`));
  run.reserveCards = ['echo', 'body-spark', 'deep-vessel', 'spark-cache', 'harvest-legendary', 'closing-chord', 'twin-orbit', 'fast-spool']
    .map((id, i) => makeSkillCard(id, `sample:late:stored:${i}`));
  run.reserveCards[3].charges = 2;
  run.reserveCards[7].charges = 1;
  run.condensedGlow = 137;
  run.artifacts = ['glow-wick', 'flash-stone', 'hearth-bloom', 'echo-vessel', 'overflow-coil', 'echo-bell',
    'dawn-loom', 'sunspool', 'galespun-spindle', 'threefold-chalice', 'night-gardener', 'moonwake-lens', 'ascent-chime'];
  run.seenArtifacts = [...run.artifacts];
  run.artifactCharges = { 'glow-wick': 3, 'flash-stone': 2 };
  run.treasureGifts = { vessel: 1, wick: 1, toll: 1, seal: 1 };
  run.treasureCapacity = 10;
  run.nextFlightPact = 'night-ledger';

  // Follow actual connected map sites to a late ordinary round. This keeps the
  // draft, challenge, chapter and route identities consistent with a real run.
  while (run.step < run.map.length) {
    const choices = getChoices(run);
    const node = choices.find(site => site.type === 'flight' && !site.elite && site.row >= 4) || choices[0];
    selectNode(run, node.id);
    if (node.type === 'flight' && !node.elite && node.row >= 4) break;
    run.step = node.row + 1;
    run.phase = 'map';
  }
  run.current.bonusId = 'gilded';
  beginFlightAttempt(run);
  markFlightAttemptStarted(run);
  finishFlight(run, { success: true, flame: 100, collected: 26, bodyFuelCollected: 18, collectorPickups: 8,
    condensedGlow: 18, pickupOverflow: 180,
    artifactCharges: { 'glow-wick': 0, 'flash-stone': 0 },
    artifactActivations: { 'glow-wick': 3, 'flash-stone': 2, 'hearth-bloom': 5, 'overflow-coil': 4,
      'echo-bell': 5, 'dawn-loom': 4, sunspool: 4, 'galespun-spindle': 3, 'threefold-chalice': 2,
      'night-gardener': 5, 'moonwake-lens': 3, 'ascent-chime': 4 },
    routeBonus: { id: 'gilded', eligible: true, complete: true, target: 4, progress: 5, packed: 18 } });
  settleCheckpoint(state);
}

export function createCardInspectorState(params = new URLSearchParams()) {
  const state = newState();
  state.profile.tutorialComplete = true;
  state.settings.skipTutorial = true;
  state.run = createRun(state.profile, 'cards-workbench-sample', 1, { cards: true });
  const run = state.run;
  run.startingGiftId = 'card:body-spark';
  run.guideSkipped = true;
  run.mountedCards = ['echo', 'spark-cache', 'deep-vessel'].map((id, i) => makeSkillCard(id, `sample:${i}`));
  run.mountedCards[1].charges = 4;
  run.reserveCards = ['body-spark', 'spark-cache', 'harvest-rare', 'harvest-legendary', 'cache-handling', 'flash-handling'].map((id, i) => makeSkillCard(id, `sample:stored:${i}`));
  run.reserveCards[1].charges = 2;
  if (params.get('deck') === 'large') {
    for (let i = 0; i < 120; i++) run.reserveCards.push(makeSkillCard(['body-spark', 'deep-vessel', 'harvest-rare', 'harvest-legendary'][i % 4], `sample:large:${i}`));
  }
  run.condensedGlow = 90;
  if (params.get('scenario') === 'departure') {
    run.mountedCards = ['lift-guide', 'rhythm', 'harvest-common'].map((id, index) => makeSkillCard(id, `sample:departure:${index}`));
    selectNode(run, getChoices(run).find(node => node.type === 'flight').id);
    return state;
  }
  if (params.get('scenario') === 'pack') {
    if (params.get('late') === '1') {
      prepareLateGamePack(state);
      return state;
    }
    const node = getChoices(run).find(n => n.type !== 'support');
    selectNode(run, node.id);
    run.current.bonusId = 'gilded';
    run.artifacts = ['flash-stone'];
    run.artifactCharges = { 'flash-stone': 2 };
    beginFlightAttempt(run);
    markFlightAttemptStarted(run);
    finishFlight(run, { success:true, flame:50, collected:6,
      artifactCharges:{'flash-stone':1}, artifactActivations:{'flash-stone':1},
      routeBonus:{id:'gilded', eligible:true, complete:true, target:4, progress:4} });
    settleCheckpoint(state);
    return state;
  }
  if (params.get('slots') === '5') {
    run.cardSlots = 5;
    run.mountedCards.push(makeSkillCard('chameleon', 'sample:3'), makeSkillCard('harvest-legendary', 'sample:4'));
  }
  if (params.get('scenario') === 'reward') prepareCardInspectorReward(run, params.get('reward') === 'edge-reach' ? 'edge-reach' : 'harvest-rare');
  if (params.get('scenario') === 'proximity') run.reserveCards.push(makeSkillCard('edge-reach', 'sample:edge-reach'));
  if (params.get('scenario') === 'closed-eye') {
    run.nextFlightPact = 'blind-pilgrim';
    run.mountedCards = ['lantern-lens', 'climb', 'harvest-common'].map((id, slot) =>
      makeSkillCard(id, 'sample:closed-eye:' + slot));
  }
  if (params.get('scenario') === 'combos') {
    run.companions=['collector'];run.companionRole='collector';
    run.artifacts=['dawn-loom','echo-bell','wayward-seed'];
    run.mountedCards=['rhythm','harvest-common','ring-spring'].map((id,i)=>makeSkillCard(id,`sample:combo:${i}`));
    run.reserveCards=['toll-bell','echo','deep-vessel','harvest-rare'].map((id,i)=>makeSkillCard(id,`sample:stored:combo:${i}`));
  }
  if (params.get('scenario') === 'rowcraft') {
    run.companions = ['collector']; run.companionRole = 'collector';
    run.cardSlots = 5;
    run.mountedCards = ['echo', 'body-spark', 'kindling-bead', 'refrain', 'closing-chord'].map((id, i) => makeSkillCard(id, `sample:rowcraft:${i}`));
    run.reserveCards = ['use-doubler', 'ember-feeder', 'spark-cache', 'fast-spool', 'devourer', 'edge-reach'].map((id, i) => makeSkillCard(id, `sample:stored:rowcraft:${i}`));
  }
  if (params.get('scenario') === 'new-common') {
    run.cardSlots = 5;
    run.mountedCards = ['growth-ring', 'wind-feather', 'wick-doubler', 'fast-spool', 'body-spark'].map((id, i) => makeSkillCard(id, `sample:new-common:${i}`));
    run.reserveCards.push(makeSkillCard('echo', 'sample:new-common:echo'));
  }
  if (['dream', 'dream-rest'].includes(params.get('scenario'))) {
    run.mountedCards = ['dream', 'lift-guide', 'deep-vessel'].map((id, i) => makeSkillCard(id, `sample:dream:${i}`));
    const node = run.map.flat().find(n => n.kind === (params.get('scenario') === 'dream-rest' ? 'camp' : 'elite'));
    run.current = node; run.step = node.row; run.path = [node.id];
    run.phase = node.kind === 'camp' ? 'support' : 'briefing';
  }
  if (params.get('scenario') === 'rest') {
    if (run.cardReward) run.cardReward.uiAcknowledged = true;
    const node = run.map.flat().find(n => n.kind === 'camp');
    run.current = node;
    run.step = node.row;
    run.path = [node.id];
    run.phase = 'support';
    getSupportChoices(run, state.profile);
  }
  if (params.get('scenario') === 'starter') {
    delete run.startingGiftId;
    run.mountedCards = [null, null, null];
    run.reserveCards = [];
    delete run.cardReward;
  }
  return state;
}
