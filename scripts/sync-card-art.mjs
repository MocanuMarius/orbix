// Copies the approved 48x48 card pictures from the design lab into the player folder and
// regenerates dist/card-art-files.mjs (id -> path). The path literals are what
// scripts/pwa-assets.mjs follows, so every picture lands in the offline list.
//   node scripts/sync-card-art.mjs
import {readFile, writeFile, copyFile, mkdir, readdir, unlink} from 'node:fs/promises';
const src = new URL('../dist/design-lab/assets/cardart/cards/', import.meta.url);
const out = new URL('../dist/assets/cards/art/', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('manifest.json', src), 'utf8'));
await mkdir(out, {recursive: true});
const ids = Object.keys(manifest).sort();
for (const id of ids) await copyFile(new URL(manifest[id].file, src), new URL(`${id}.svg`, out));
for (const f of await readdir(out)) if (f.endsWith('.svg') && !ids.includes(f.slice(0, -4))) await unlink(new URL(f, out));
const lines = ids.map(id => `  '${id}': 'assets/cards/art/${id}.svg',`).join('\n');
await writeFile(new URL('../dist/card-art-files.mjs', import.meta.url),
  `// Generated by scripts/sync-card-art.mjs. Do not edit.\nexport const CARD_ART_FILES = Object.freeze({\n${lines}\n});\n`);
console.log(ids.length + ' card pictures synced');
