// Regenerates dist/ui-icons.mjs from dist/assets/ui/icons/*.svg (the approved v2.0-icons set) plus dist/assets/ui/spark.svg.
// Run: node scripts/build-ui-icons.mjs        Check only: node scripts/build-ui-icons.mjs --check
// The icon drawings come from dist/design-lab/assets/icons2/build.mjs (the sheet generator); copies of the approved SVGs live in the game folder
// because the design lab is not published. Each 1x1 rect is merged into horizontal runs, so the module stays small.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = path.join(root, 'dist/assets/ui/icons');
const target = path.join(root, 'dist/ui-icons.mjs');

export function parseIconSvg(text) {
  const grid = Number(/viewBox="0 0 (\d+) \1"/.exec(text)?.[1]);
  const layers = [];
  for (const m of text.matchAll(/<path fill="(#[0-9a-fA-F]{6})" d="([^"]*)"\/>/g)) {
    const pixels = new Map();
    for (const p of m[2].matchAll(/M(\d+) (\d+)h1v1h-1z/g)) pixels.set(`${p[1]},${p[2]}`, [Number(p[1]), Number(p[2])]);
    const rows = new Map();
    for (const [x, y] of pixels.values()) (rows.get(y) || rows.set(y, []).get(y)).push(x);
    let d = '';
    for (const y of [...rows.keys()].sort((a, b) => a - b)) {
      const xs = rows.get(y).sort((a, b) => a - b);
      for (let i = 0; i < xs.length;) {
        let j = i; while (j + 1 < xs.length && xs[j + 1] === xs[j] + 1) j++;
        d += `M${xs[i]} ${y}h${xs[j] - xs[i] + 1}v1h-${xs[j] - xs[i] + 1}z`; i = j + 1;
      }
    }
    layers.push([m[1].toLowerCase(), d]);
  }
  return {grid, layers};
}

export function buildModule() {
  const files = fs.readdirSync(iconDir).filter(f => f.endsWith('.svg')).sort();
  const sources = files.map(f => [f.slice(0, -4), path.join(iconDir, f)]);
  sources.push(['spark', path.join(root, 'dist/assets/ui/spark.svg')]);
  sources.sort((a, b) => a[0].localeCompare(b[0]));
  const entries = sources.map(([name, file]) => {
    const {grid, layers} = parseIconSvg(fs.readFileSync(file, 'utf8'));
    if (!grid || !layers.length) throw new Error(`cannot read ${file}`);
    return `  '${name}': [${grid}, ${JSON.stringify(layers)}]`;
  });
  return `// GENERATED by scripts/build-ui-icons.mjs from dist/assets/ui/icons/*.svg and dist/assets/ui/spark.svg. Do not edit by hand.
// Approved icon set v2.0-icons. Every icon is drawn on a whole pixel grid (16, or 24 for map stops) and must be shown at a whole multiple of it.
const ICONS = {
${entries.join(',\n')}
};
export const UI_ICON_NAMES = Object.freeze(Object.keys(ICONS));
export const uiIconGrid = name => ICONS[name]?.[0] ?? 0;
/** Inline SVG for an approved icon. size must be a whole multiple of the icon's grid (default: the grid itself). */
export function uiIcon(name, {size, className = ''} = {}) {
  const icon = ICONS[name];
  if (!icon) throw new Error(\`Unknown UI icon: \${name}\`);
  const [grid, layers] = icon, px = Math.max(1, Math.round((size || grid) / grid)) * grid;
  return \`<svg class="ui-icon\${className ? ' ' + className : ''}" data-ui-icon="\${name}" width="\${px}" height="\${px}" style="--ui-size:\${px}px" viewBox="0 0 \${grid} \${grid}" shape-rendering="crispEdges" aria-hidden="true" focusable="false">\${layers.map(([fill, d]) => \`<path fill="\${fill}" d="\${d}"/>\`).join('')}</svg>\`;
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = buildModule();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== next) { console.error('dist/ui-icons.mjs is out of date: run node scripts/build-ui-icons.mjs'); process.exit(1); }
  } else { fs.writeFileSync(target, next); console.log('wrote dist/ui-icons.mjs', next.length, 'bytes'); }
}
