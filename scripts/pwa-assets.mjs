// Release packaging: follow the shipped desktop and phone entry points. This
// keeps experimental renderers and unused texture atlases off the device.
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {extname, dirname, posix} from 'node:path';
const dist = new URL('../dist/', import.meta.url);
const game = await readFile(new URL('game.html', dist), 'utf8');
const release = /src="app\.mjs\?v=([^"]+)"/.exec(game)?.[1];
if (!release) throw new Error('Expected a release stamp on the game entry module');
const files = new Set();
const hash = createHash('sha256');
async function visit(file) {
  if (files.has(file)) return;
  files.add(file);
  const data = await readFile(new URL(file, dist));
  hash.update(file).update(data);
  const ext = extname(file);
  if (!['.html', '.mjs', '.js', '.css', '.webmanifest'].includes(ext)) return;
  const source = data.toString();
  let refs = [];
  if (ext === '.html') refs = [...source.matchAll(/(?:src|href)=["']([^"']+)["']/g)].map(match => match[1]);
  if (ext === '.mjs' || ext === '.js') {
    refs = [...source.matchAll(/(?:\bfrom\s*|\bimport\s*\(?\s*)["'](\.[^"']+)["']/g)].map(match => match[1]);
    refs.push(...[...source.matchAll(/["'`]((?:\.\/)?assets\/[\w./-]+\.(?:mp3|mp4|png|svg|ttf|webp|jpg))["'`]/g)].map(match => match[1]));
  }
  if (ext === '.css') refs = [...source.matchAll(/url\(\s*["']?([^)'"]+)["']?\s*\)/g)].map(match => match[1]);
  if (ext === '.webmanifest') refs = JSON.parse(source).icons.map(icon => icon.src);
  for (const ref of refs) {
    if (/^[a-z]+:|^#|^\/\//i.test(ref)) continue;
    // Links back to the game's root refer to its cached index document.
    const path = ref.split(/[?#]/)[0];
    const relative = path.endsWith('/') ? path + 'index.html' : path;
    if (relative) await visit(posix.normalize(posix.join(dirname(file).replaceAll('\\','/'), relative)));
  }
}
for (const entry of ['index.html', 'game.html', 'cards.html', 'card-workbench.html', 'card-combos.html', 'card-art-preview.html', 'collector-art.html', 'rhythm-preview.html', 'loading.html', 'preview.html', 'spark-preview.html','skills-preview.html','lanterns.html','black-holes.html','absorption-fluid.html','ecology-preview.html','music-preview.html','resonance-preview.html','boundary-preview.html','assets/previews/terrain-light-comparison.png', 'assets/previews/pixelation-deck.webp', 'assets/previews/pixelation-flight.webp', 'assets/help/collector-orbit.webp', 'assets/help/collector-fetch.webp', 'assets/previews/collector-tether/after.mp4', 'assets/previews/collector-tether/before.mp4', 'assets/previews/collector-tether/capture-notes.json', 'assets/previews/collector-tether/reel-back.png', 'assets/previews/collector-tether/reel-front.png', 'assets/previews/collector-tether/reel-near.png', 'assets/previews/collector-tether/reel.mp4', 'assets/previews/collector-tether/wake-first-paint-without.png', 'assets/previews/collector-tether/wake-first-paint.png']) await visit(entry);
const list = {release, revision: hash.digest('hex').slice(0, 12), files: [...files].sort()};
await writeFile(new URL('offline-list.js', dist), '// Generated by scripts/pwa-assets.mjs.\nconst WISP_OFFLINE = ' + JSON.stringify(list, null, 2) + ';\n');
console.log(list.files.length + ' offline files · ' + list.release + ' · ' + list.revision);
