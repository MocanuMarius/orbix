import assert from 'node:assert/strict';
import * as M from '../dist/model.mjs';
import {getGlowCapacity,formatGlow,glowText} from '../dist/vitality.mjs';
import {WispFlight} from '../dist/flight.mjs';
import {pickupGuideMarkup} from '../dist/pickup-guide.mjs';
import {getMapStopInfo} from '../dist/map-guide.mjs';
import {runProgressMarkup} from '../dist/run-menu.mjs';
const fresh=()=>{const s=M.newState();s.run=M.createRun(s.profile,'glow-builds');return s;};
const buy=(s,...ids)=>ids.forEach(id=>assert.ok(M.buyCheckpointSkill(s,id),id));
const state=fresh(),r=state.run;
assert.equal(r.embers,90);assert.ok(M.chooseStartingSkill(state,'main-efficiency'));
buy(state,'main-reservoir','main-vast-vessel');
assert.equal(r.embers,10);assert.equal(r.flame,105);assert.equal(getGlowCapacity(r),140);
assert.equal(formatGlow(r.flame,140),'75%');
assert.match(runProgressMarkup(r),/75% GLOW/);
assert.ok(M.selectNode(r,M.getChoices(r)[0].id));
assert.equal(M.canBuyCheckpointSkills(state),false);
assert.ok(M.beginFlightAttempt(r));
assert.ok(M.finishFlight(r,{success:true,flame:134,collected:2,embers:2}));
assert.equal(r.flame,134,'Clear must preserve fuel above the old 100 cap');
const data=new Map(),storage={setItem:(k,v)=>data.set(k,v),getItem:k=>data.get(k)};
assert.ok(M.saveState(state,storage));const loaded=M.loadState(storage);
assert.equal(loaded.run.flame,134);assert.equal(getGlowCapacity(loaded.run),140);

function rest(s,boon=0){const r=s.run;r.step=1;r.path=['completed-flight'];r.current={id:'probe-rest',kind:'camp',type:'support',row:1};r.phase='support';r.flame=30;
 assert.ok(M.resolveSupport(r,boon,s.profile));assert.ok(r.restReady);r.embers=200;
}
const rested=fresh();M.chooseStartingSkill(rested,'main-efficiency');rest(rested);
assert.equal(rested.run.flame,100);buy(rested,'main-reservoir');assert.equal(rested.run.flame,120);
buy(rested,'main-vast-vessel');assert.equal(rested.run.flame,140);
const gathered=fresh();M.chooseStartingSkill(gathered,'main-efficiency');rest(gathered,1);
const gatheredFuel=gathered.run.flame;buy(gathered,'main-reservoir');assert.equal(gathered.run.flame,gatheredFuel,'Gather does not fill newly bought space');
rest(gathered);assert.equal(gathered.run.flame,120);
gathered.run.testMode=true;buy(gathered,'main-vast-vessel','main-cache-feast');
assert.equal(getGlowCapacity(gathered.run),120);assert.equal(gathered.run.flame,120);
assert.equal(gathered.run.skills['main-vast-vessel'],undefined);

const reserve=fresh();Object.assign(reserve.run,{skills:{'main-reservoir':1,'main-vast-vessel':1},afterglowUnlocked:true,afterglow:0});
M.selectNode(reserve.run,M.getChoices(reserve.run)[0].id);M.beginFlightAttempt(reserve.run);
M.finishFlight(reserve.run,{success:true,flame:100});
assert.equal(reserve.run.flame,84,'Afterglow threshold is 60% of upgraded capacity');
assert.equal(reserve.run.afterglow,12.8);
Object.assign(reserve.run,{phase:'briefing',flame:135,afterglow:20});
assert.equal(M.drawAfterglow(reserve.run),5);assert.equal(reserve.run.flame,140);

globalThis.requestAnimationFrame=()=>1;globalThis.cancelAnimationFrame=()=>{};
const gradient={addColorStop(){}};
const context=new Proxy({globalAlpha:1},{get:(o,k)=>o[k]??(String(k).includes('Gradient')?()=>gradient:()=>{}),set:(o,k,v)=>(o[k]=v,true)});
const canvas={style:{},getContext:()=>context,getBoundingClientRect:()=>({width:390,height:620})};
const e=new WispFlight({canvas,seed:'glow-builds',terrain:'ruins',duration:20,flame:110,companions:['collector'],modifiers:M.getRunModifiers({skills:{'main-reservoir':1,'main-cache-feast':1}})});
assert.equal(e.maxFlame,120);assert.equal(e.flame,110);
e.collect({id:'fill',kind:'light',x:e.player.x,y:e.player.y});assert.equal(e.flame,120);assert.equal(e.pickupEffects.at(-1).restored,10);
e.flame=0;e.collect({id:'fetched',kind:'light',deliveredByWisp:true,x:0,y:0});assert.equal(e.flame,24);
assert.equal(formatGlow(e.pickupEffects.at(-1).restored,e.maxFlame),'20%');
e.flame=0;e.collect({id:'cache',kind:'cache',value:3,x:0,y:0});assert.equal(e.flame,48);
assert.equal(formatGlow(e.pickupEffects.at(-1).restored,e.maxFlame),'40%');
const packetGuide=pickupGuideMarkup({maxGlow:120,discovered:['light','cache']});assert.match(packetGuide,/\+20% Glow/);
assert.equal(glowText('+24 Glow',120),'+20% Glow');
assert.match(getMapStopInfo({type:'support',kind:'event',eventIndex:2},120).summary,/20% Glow/);
e.destroy();
console.log(JSON.stringify({startingBuilds:true,capacity:140,restRefills:true,saveAndCarry:true,afterglowThreshold:true,realEnginePickups:true,capacityRelativePercentages:true}));
