// Source of the Inscription brand marks (docs/inscriptions.md). Each is drawn here on a 24×24 pixel grid in a bold brand /
// petroglyph style with engraved detail, in TWO tones: '#' = ink (the brand colour), '+' = the second tone (the same colour at half
// strength: carved inner lines, highlights, grain), '.' = empty. Silhouette first: every mark must read at 24 px (1×) on a Chain slot.
// Run: node scripts/build-inscription-glyphs.mjs        Check only: node scripts/build-inscription-glyphs.mjs --check
// Writes dist/assets/ui/inscriptions/<id>.svg (currentColor) and the root module dist/inscription-glyphs.mjs, which inlines the
// same pixels as horizontal runs (ink, second tone) plus a 1-pixel "edge" layer (the glyph grown by one pixel) used when the mark is
// burned into a slot frame. Modules under dist/ui/ import glyphs from the root module, never asset paths of their own.
// Display sizes are whole multiples only: 24 / 48 / 72 for a plain mark, 26 / 52 for a burned brand (grid 26 = 24 + edge).
