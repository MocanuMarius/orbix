const N = GRID;
const cells = (rows, tones) => { const out = new Set(); rows.forEach((row, y) => [...row].forEach((c, x) => { if (tones.includes(c)) out.add(`${x},${y}`); })); return out; };
/** Horizontal runs of a cell set as an SVG path (each run one rect). */
function runs(set) {
  const byRow = new Map();
  for (const key of set) { const [x, y] = key.split(',').map(Number); (byRow.get(y) || byRow.set(y, []).get(y)).push(x); }
  let d = '';
  for (const y of [...byRow.keys()].sort((a, b) => a - b)) {
    const xs = byRow.get(y).sort((a, b) => a - b);
    for (let i = 0; i < xs.length;) { let j = i; while (j + 1 < xs.length && xs[j + 1] === xs[j] + 1) j++; d += `M${xs[i]} ${y}h${j - i + 1}v1h-${j - i + 1}z`; i = j + 1; }
  }
  return d;
}
/** The glyph grown by one pixel (8 neighbours) minus the glyph: the lighter edge of a burned brand. Grid -1..24. */
function edge(set) {
  const out = new Set();
  for (const key of set) { const [x, y] = key.split(',').map(Number); for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) { const k = `${x + dx},${y + dy}`; if (!set.has(k)) out.add(k); } }
  return out;
}

export function validate() {
  const problems = [];
  const seen = new Map();
  for (const [id, rows] of Object.entries(GLYPHS)) {
    if (rows.length !== N || rows.some(r => r.length !== N || /[^#+.]/.test(r))) problems.push(`${id}: not a ${N}×${N} grid of #, + and .`);
    if (!rows.join('').includes('+')) problems.push(`${id}: no second-tone detail`);
    const key = rows.join('');
    if (seen.has(key)) problems.push(`${id}: same drawing as ${seen.get(key)}`);
    seen.set(key, id);
  }
  return problems;
}

const paths = id => { const rows = GLYPHS[id]; return [runs(cells(rows, '#')), runs(cells(rows, '+')), runs(edge(cells(rows, '#+')))]; };
export function buildSvg(id) {
  const [ink, cut] = paths(id);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${N}" height="${N}" viewBox="0 0 ${N} ${N}" shape-rendering="crispEdges"><path fill="currentColor" d="${ink}"/><path fill="currentColor" fill-opacity="${CUT_OPACITY}" d="${cut}"/></svg>\n`;
}

export function buildModule() {
  const entries = Object.keys(GLYPHS).map(id => `  '${id}': ['${paths(id).join("', '")}']`);
  return `// GENERATED by scripts/build-inscription-glyphs.mjs (the drawings live there). Do not edit by hand.
// One brand mark per Inscription on a ${N}×${N} pixel grid in two tones of currentColor: ink, and the engraved detail at ${CUT_OPACITY} opacity
// (CSS may recolour it through the class ins-glyph-cut). A burned brand (brand: true) adds a 1-pixel lighter edge around the mark, so
// its grid is ${N + 2} (-1..${N}). Sizes are whole multiples of the grid only, one per role (INSCRIPTION_GLYPH_SIZES).
const GLYPHS = {
${entries.join(',\n')}
};
export const INSCRIPTION_GLYPH_IDS = Object.freeze(Object.keys(GLYPHS));
export const INSCRIPTION_GLYPH_GRID = ${N};
export const INSCRIPTION_BRAND_GRID = ${N + 2};
/** One size per role. list: beside text (inspector, Replaces line, glossary, briefing); large: Scribe offers and confirms;
 * brand: burned into a Chain slot's frame; brandLarge: on an empty inscribed slot. */
export const INSCRIPTION_GLYPH_SIZES = Object.freeze({list: ${N}, large: ${N * 2}, huge: ${N * 3}, brand: ${N + 2}, brandLarge: ${(N + 2) * 2}});
/** A size is allowed when it is a whole multiple of the grid (${N}, or ${N + 2} for a burned brand). */
export const isWholeGlyphSize = (size, brand = false) => Number.isInteger(size) && size > 0 && size % (brand ? ${N + 2} : ${N}) === 0;
/** Asset path of a glyph's SVG file (relative to this module's folder, dist/). */
export const inscriptionGlyphPath = id => GLYPHS[id] ? \`assets/ui/inscriptions/\${id}.svg\` : '';
/** Inline SVG of an Inscription's brand mark. role: list | large | huge | brand | brandLarge (sets the size and a class
 * ins-glyph-<role>). size: a whole multiple of the grid (anything else is rounded to the nearest whole multiple, never scaled by
 * a fraction). brand: add the lighter burned edge (implied by the brand roles). */
export function inscriptionGlyph(id, {size, role = '', className = '', brand = false} = {}) {
  const glyph = GLYPHS[id];
  if (!glyph) return '';
  const isBrand = brand || role === 'brand' || role === 'brandLarge';
  const grid = isBrand ? ${N + 2} : ${N}, want = size || INSCRIPTION_GLYPH_SIZES[role] || grid, px = Math.max(1, Math.round(want / grid)) * grid;
  const box = isBrand ? '-1 -1 ${N + 2} ${N + 2}' : '0 0 ${N} ${N}';
  const cls = \`ins-glyph\${isBrand ? ' ins-brand' : ''}\${role ? ' ins-glyph-' + role : ''}\${className ? ' ' + className : ''}\`;
  return \`<svg class="\${cls}" data-ins-glyph="\${id}" width="\${px}" height="\${px}" viewBox="\${box}" shape-rendering="crispEdges" aria-hidden="true" focusable="false">\${isBrand ? \`<path class="ins-brand-edge" d="\${glyph[2]}"/>\` : ''}<path class="ins-glyph-ink" fill="currentColor" d="\${glyph[0]}"/><path class="ins-glyph-cut" fill="currentColor" fill-opacity="${CUT_OPACITY}" d="\${glyph[1]}"/></svg>\`;
}
`;
}

