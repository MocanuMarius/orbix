// The courses the simulated pilots fly (5 run seeds x 6 stops) with how hard each is, and links to fly them yourself (?simrun, dist/sim-replay.mjs).
//   node scripts/balance/sim-courses.mjs --pilot=player-average [--trials=10]   -> outputs/balance/sim-courses/<pilot>.json  (run once per pilot, in parallel)
//   node scripts/balance/sim-courses.mjs --report                               -> outputs/balance/sim-courses.md
// A trial = the pilot flies that stop once, from the stop's default start state (dist/sim-replay.mjs SIM_START), with its own random stream.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
process.argv.push('--importOnly');
const { createSim } = await import('./starter-sim.mjs');
const { simRoute, FIRST_STOPS } = await import('./app-flight.mjs');
const { makeRun, M, P } = await import('./real-flight-check.mjs');
const { SIM_START } = await import('../../dist/sim-replay.mjs');
const { SPARK_UNITS } = await import('../player-pilot.mjs');
const args = Object.fromEntries(process.argv.slice(2).map(a => { const [k, ...v] = a.replace(/^--/, '').split('='); return [k, v.join('=') || true]; }));
const SEEDS = ['sb0', 'sb1', 'sb2', 'sb3', 'sb4'], PILOTS = ['player-beginner', 'player-average', 'player-good'];
const dir = fileURLToPath(new URL('../../outputs/balance/sim-courses/', import.meta.url)), mdFile = fileURLToPath(new URL('../../outputs/balance/sim-courses.md', import.meta.url));
const HOVER_LIFT_SECONDS = 1.367, LIFT_SPARKS = 3;   // a Lift every 1.367 s keeps altitude (scripts/player-pilot.mjs liftHeight); one Lift costs 10 units = 3 Sparks
const PUBLIC = 'https://mocanumarius.github.io/orbix/game.html', LOCAL = 'http://localhost:4173/game.html';
const PENDING = ['pendingChest', 'pendingTemporary', 'cardDraft', 'cardReward', 'flightReward'];

async function courseInfo(sim) {
  const info = {};
  for (const seed of SEEDS) {
    const { path } = simRoute(seed, ['lift-guide'], makeRun), run = makeRun(['lift-guide'], { seed }); let n = 0;
    for (const id of path) {
      const pick = M.getChoices(run).find(x => x.id === id); M.selectNode(run, id);
      if (pick.type === 'flight') {
        n++; const config = sim.flightConfig(run, pick, 'player-good'); let e = null;
        config.prepareEngine = x => { e = x; throw new Error('captured'); };
        try { sim.simulate(config); } catch (err) { if (err.message !== 'captured') throw err; }
        const supply = e.layout.embers.filter(p => !p.generated && !p.harmful).reduce((a, p) => { const f = P.getPickupSpec(p).fuel; return a + (f ? f + e.fuelBonus + e.mod.cacheFuelBonus : 0); }, 0) / SPARK_UNITS;
        info[`${seed}:${n}`] = { name: pick.locationName || pick.name, terrain: pick.terrain, duration: pick.duration, supply: Math.round(supply), need: Math.round(pick.duration / HOVER_LIFT_SECONDS * LIFT_SPARKS), elite: !!pick.elite };
      }
      if (pick.kind === 'camp') M.resolveSupport(run, 0);
      run.phase = 'map'; run.step = pick.row + 1; run.current = null; run.attemptActive = false; for (const k of PENDING) delete run[k];
    }
  }
  return info;
}

if (args.report) {
  const sim = await createSim({ style: 'player-good' }), info = await courseInfo(sim), data = {};
  for (const p of PILOTS) { const f = `${dir}${p}.json`; if (fs.existsSync(f)) data[p] = JSON.parse(fs.readFileSync(f, 'utf8')); }
  const rows = [];
  for (const seed of SEEDS) for (let stop = 1; stop <= FIRST_STOPS; stop++) {
    const key = `${seed}:${stop}`, c = info[key], per = {};
    for (const p of Object.keys(data)) {
      const t = data[p][key] || [], fails = t.filter(x => !x.ok), causes = {}; fails.forEach(x => { causes[x.cause] = (causes[x.cause] || 0) + 1; });
      const top = Object.entries(causes).sort((a, b) => b[1] - a[1])[0]; per[p] = { share: t.length ? fails.length / t.length : null, n: t.length, cause: top ? top[0] : '-' };
    }
    const shares = Object.values(per).map(x => x.share).filter(x => x != null), mean = shares.length ? shares.reduce((a, b) => a + b, 0) / shares.length : 0;
    rows.push({ seed, stop, key, c, per, mean });
  }
  const worst = new Set([...rows].sort((a, b) => b.mean - a.mean).slice(0, 6).map(r => r.key));
  const pct = x => x == null ? '-' : `${Math.round(x * 100)}%`, nTrials = Object.values(data)[0]?.[rows[0].key]?.length || '?';
  const lines = ['# Sim courses: what the pilots fly, and links to fly it yourself', '',
    'Generated by `scripts/balance/sim-courses.mjs`. Flight seeds and route are identical to the pilots of `scripts/balance/starter-balance.mjs`; the flight is the app\'s own flight (`tests/sim-matches-app.test.mjs`). A stop = one flight of Map 1 on the pilots\' route; Lift Guide mounted, nothing else; start Meter and hearts = the pilots\' typical state at that stop (`SIM_START`: Meter 30/15/30/30/15/15 Sparks, hearts 3/3/3/3/3/2).', '',
    `**Supplied** = Sparks lying in the course. **Hover needs** = Sparks an efficient hover costs for the whole duration (one Lift every ${HOVER_LIFT_SECONDS} s, ${LIFT_SPARKS} Sparks each); the starting Meter covers the first 15 to 30. Pilot columns = share of ${nTrials} single attempts that fell, with the most common cause (fuel = the Meter ran out; obstacle / terrain / boundary = a hit). **W** marks the 6 worst stops (highest mean failure over the three pilots).`, '',
    '| seed | stop | W | course | s | supplied | hover needs | beginner | average | good | public link | local link |', '|---|---|---|---|---|---|---|---|---|---|---|---|'];
  for (const r of rows) {
    const cell = p => r.per[p] ? `${pct(r.per[p].share)} ${r.per[p].cause}` : '-';
    lines.push(`| ${r.seed} | ${r.stop} | ${worst.has(r.key) ? '**W**' : ''} | ${r.c.name}${r.c.elite ? ' (Elite)' : ''} | ${r.c.duration} | ${r.c.supply} | ${r.c.need} | ${cell('player-beginner')} | ${cell('player-average')} | ${cell('player-good')} | [open](${PUBLIC}?simrun=${r.seed}&stop=${r.stop}) | [open](${LOCAL}?simrun=${r.seed}&stop=${r.stop}) |`);
  }
  lines.push('', '## The 6 worst stops', '');
  for (const r of rows.filter(r => worst.has(r.key)).sort((a, b) => b.mean - a.mean)) lines.push(`- ${r.seed} stop ${r.stop}, ${r.c.name}: mean failure ${pct(r.mean)}. ${PUBLIC}?simrun=${r.seed}&stop=${r.stop}  |  ${LOCAL}?simrun=${r.seed}&stop=${r.stop}`);
  lines.push('', 'Options on any link: `&card=<starter id>` adds one card, `&meter=<Sparks>&hearts=<n>` overrides the start state. After a flight a panel offers Next stop (carries Meter and hearts over), Retry and Exit. The run never touches the save. Turn on Settings > Advanced > Record play first to log your flights (they carry the flight seed, comparable with the pilots\').', '');
  fs.writeFileSync(mdFile, lines.join('\n')); console.log([...worst].join(' '));
} else {
  const sim = await createSim({ style: args.pilot }), trials = Number(args.trials || 10), out = {};
  for (const seed of SEEDS) for (let stop = 1; stop <= FIRST_STOPS; stop++) {
    const key = `${seed}:${stop}`; out[key] = [];
    for (let k = 1; k <= trials; k++) {
      const m = sim.flyRun(['lift-guide'], seed, { restBelow: 88, startAt: { stop, sparks: SIM_START[stop - 1].sparks, hearts: SIM_START[stop - 1].hearts }, trial: k, once: true });
      out[key].push({ ok: m.cleared === 1, cause: m.cleared === 1 ? null : Object.entries(m.deaths).sort((a, b) => b[1] - a[1])[0][0] });
    }
    console.error(args.pilot, key, out[key].filter(x => !x.ok).length + '/' + trials);
  }
  fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(`${dir}${args.pilot}.json`, JSON.stringify(out));
}
